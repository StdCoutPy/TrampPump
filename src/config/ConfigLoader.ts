/**
 * @module ConfigLoader
 * Единственная точка входа для получения конфигурации приложения. 
 * Абстрагирует, откуда именно берутся настройки (встроенные, JSON, сетевые).
 */

import AppConfig,{getEmbeddedDefaultConfig}  from './AppConfig';
/**
 * Сервис, отвечающий за получение настроек приложения. Работает асинхронно для поддержки будущей загрузки из внешних источников.
 */
export class ConfigLoader {

    /**
     * Асинхронно загружает и возвращает полную конфигурацию приложения.
     * @returns Промис, разрешающийся объектом AppConfig.
     */
    public static async loadConfig(): Promise<AppConfig> {
        // Имитация задержки ввода/вывода для проверки асинхронности.
        await new Promise(resolve => setTimeout(resolve, 10));

        // В настоящий момент мы загружаем настроенную тестовую конфигурацию.
        const config = getEmbeddedDefaultConfig();

        // Здесь будет добавляться логика валидации и проверок целостности полученных данных.
        // Если загрузка из файла/сети завершится ошибкой, она должна быть обработана здесь.
        
        return config;
    }
}
